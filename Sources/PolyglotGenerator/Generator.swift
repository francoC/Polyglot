//
//  Generator.swift
//  PolyglotGenerator
//
//  Generates .strings and .stringsdict files from translation data
//

import Foundation
import PolyglotCore

/// Generator for iOS localization bundle files
public class Generator {
    private let fileManager = FileManager.default

    public init() {}

    // MARK: - CLDR Plural Category Forwarding Shim

    /// Returns the CLDR plural categories required for the given BCP 47 language code.
    /// Delegates to PluralCategory.requiredCategories(for:) in PolyglotCore.
    public static func requiredCategories(for languageCode: String) -> [PluralCategory] {
        PluralCategory.requiredCategories(for: languageCode)
    }

    // MARK: - Public API

    /// Generate iOS localization bundle from translation entries.
    /// Creates .lproj directories with Localizable.strings and Localizable.stringsdict files.
    public func generateBundle(
        from entries: [TranslationEntry],
        outputDirectory: URL,
        version: String? = nil
    ) throws {
        var allLanguageCodes: Set<String> = []
        for entry in entries {
            for languageCode in entry.translations.keys {
                allLanguageCodes.insert(languageCode)
            }
        }
        if allLanguageCodes.isEmpty { allLanguageCodes.insert("en") }

        for languageCode in allLanguageCodes.sorted() {
            let lprojURL = outputDirectory.appendingPathComponent("\(languageCode).lproj")
            try fileManager.createDirectory(at: lprojURL, withIntermediateDirectories: true)

            let stringsURL = lprojURL.appendingPathComponent("Localizable.strings")
            try generateStringsFile(entries: entries, languageCode: languageCode, outputURL: stringsURL, version: version)

            let pluralEntries = entries.filter { $0.key.isPlural && entryHasTranslationForLanguage($0, languageCode: languageCode) }
            if !pluralEntries.isEmpty {
                let stringsDictURL = lprojURL.appendingPathComponent("Localizable.stringsdict")
                try generateStringsDictFile(entries: pluralEntries, languageCode: languageCode, outputURL: stringsDictURL)
            }
        }
    }

    private func entryHasTranslationForLanguage(_ entry: TranslationEntry, languageCode: String) -> Bool {
        return entry.translations[languageCode] != nil || languageCode == "en"
    }

    // MARK: - .strings Generation

    private func generateStringsFile(
        entries: [TranslationEntry],
        languageCode: String,
        outputURL: URL,
        version: String?
    ) throws {
        var content = "/* \n"
        content += " * Localizable.strings\n"
        content += " * Generated by Polyglot\n"
        if let version = version { content += " * Version: \(version)\n" }
        content += " * Language: \(languageCode)\n"
        content += " */\n\n"

        // Group by context (falling back to file name), preserving sort within each group
        let groupKey: (TranslationEntry) -> String = { entry in
            entry.key.context ?? URL(fileURLWithPath: entry.key.filePath).deletingPathExtension().lastPathComponent
        }
        let groups = Dictionary(grouping: entries.sorted { $0.key.key < $1.key.key }, by: groupKey)

        for group in groups.keys.sorted() {
            content += "/* \(group) */\n"
            for entry in groups[group]! {
                let translation: String
                if let t = entry.translations[languageCode] {
                    translation = t.text
                } else if languageCode == "en" {
                    translation = entry.key.baseText
                } else {
                    continue
                }
                let denormalized = try StringKey.denormalize(text: translation, placeholders: entry.key.placeholders)
                content += "\"\(escapeString(entry.key.key))\" = \"\(escapeString(denormalized))\";\n"
            }
            content += "\n"
        }

        try content.write(to: outputURL, atomically: true, encoding: .utf8)
    }

    // MARK: - .stringsdict Generation

    private func generateStringsDictFile(
        entries: [TranslationEntry],
        languageCode: String,
        outputURL: URL
    ) throws {
        var xml  = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
        xml += "<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" "
        xml += "\"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n"
        xml += "<plist version=\"1.0\">\n"
        xml += "<dict>\n"

        let required = Generator.requiredCategories(for: languageCode)
        let sortedEntries = entries.sorted { $0.key.key < $1.key.key }

        for entry in sortedEntries {
            // Resolve the plural forms to write for each category:
            // 1. Translation.pluralForms[category] (real translated form)
            // 2. StringKey.pluralForms[category]   (source form as placeholder)
            // 3. StringKey.baseText                (ultimate fallback)
            let translationForms: [PluralCategory: String]?
            if let t = entry.translations[languageCode] {
                translationForms = t.pluralForms
            } else if languageCode == "en" {
                translationForms = entry.key.pluralForms
            } else {
                continue
            }

            let escapedKey = escapeXMLString(entry.key.key)
            xml += "  <key>\(escapedKey)</key>\n"
            xml += "  <dict>\n"
            xml += "    <key>NSStringLocalizedFormatKey</key>\n"
            xml += "    <string>%#@value@</string>\n"
            xml += "    <key>value</key>\n"
            xml += "    <dict>\n"
            xml += "      <key>NSStringFormatSpecTypeKey</key>\n"
            xml += "      <string>NSStringPluralRuleType</string>\n"
            xml += "      <key>NSStringFormatValueTypeKey</key>\n"
            xml += "      <string>d</string>\n"

            for category in required {
                let text: String
                if let form = translationForms?[category] {
                    text = form
                } else if let sourceForm = entry.key.pluralForms?[category] {
                    text = sourceForm
                } else {
                    text = entry.key.baseText
                }
                let denormalized = try StringKey.denormalize(text: text, placeholders: entry.key.placeholders)
                xml += "      <key>\(category.rawValue)</key>\n"
                xml += "      <string>\(escapeXMLString(denormalized))</string>\n"
            }

            xml += "    </dict>\n"
            xml += "  </dict>\n"
        }

        xml += "</dict>\n"
        xml += "</plist>\n"

        try xml.write(to: outputURL, atomically: true, encoding: .utf8)
    }

    // MARK: - Escape Helpers

    private func escapeString(_ string: String) -> String {
        var s = string
        s = s.replacingOccurrences(of: "\\", with: "\\\\")
        s = s.replacingOccurrences(of: "\"", with: "\\\"")
        s = s.replacingOccurrences(of: "\n", with: "\\n")
        s = s.replacingOccurrences(of: "\r", with: "\\r")
        s = s.replacingOccurrences(of: "\t", with: "\\t")
        return s
    }

    private func escapeXMLString(_ string: String) -> String {
        var s = string
        s = s.replacingOccurrences(of: "&",  with: "&amp;")
        s = s.replacingOccurrences(of: "<",  with: "&lt;")
        s = s.replacingOccurrences(of: ">",  with: "&gt;")
        s = s.replacingOccurrences(of: "\"", with: "&quot;")
        s = s.replacingOccurrences(of: "'",  with: "&apos;")
        return s
    }
}

public enum GeneratorError: Error {
    case invalidOutputDirectory
    case fileWriteError(Error)
    case invalidTranslationData
    case missingLanguageCode
}
